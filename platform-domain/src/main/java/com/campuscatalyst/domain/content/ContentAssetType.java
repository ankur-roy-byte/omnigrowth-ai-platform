package com.campuscatalyst.domain.content;

/**
 * Types of content assets that can be created.
 */
public enum ContentAssetType {
    /**
     * Social media caption
     */
    CAPTION,

    /**
     * Video script
     */
    SCRIPT,

    /**
     * Blog post or article
     */
    BLOG,

    /**
     * Email content
     */
    EMAIL,

    /**
     * Short-form description
     */
    DESCRIPTION,

    /**
     * Hashtags and tags
     */
    TAGS
}
